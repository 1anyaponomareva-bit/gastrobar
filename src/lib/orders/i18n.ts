export function isOrdersLang(value: string | null | undefined): value is OrdersLang {
  return value === "ru" || value === "en" || value === "vn";
}

export function readOrdersLang(): OrdersLang {
  if (typeof window === "undefined") return "ru";
  try {
    for (const key of [ORDERS_LANG_KEY, "gastrofood-erp-lang", "lang"]) {
      const raw = window.localStorage.getItem(key);
      const normalized = raw === "vi" ? "vn" : raw;
      if (isOrdersLang(normalized)) return normalized;
    }
  } catch {
    /* private mode */
  }
  return "ru";
}

export function writeOrdersLang(lang: OrdersLang): void {
  try {
    window.localStorage.setItem(ORDERS_LANG_KEY, lang);
  } catch {
    /* private mode */
  }
}

export function ordersT(lang: OrdersLang, key: string, vars?: Record<string, string | number>): string {
  let text = TABLE[lang][key] ?? TABLE.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function productLabel(lang: OrdersLang, nameEn: string, nameVn: string): string {
  if (lang === "vn") return (nameVn || nameEn).trim();
  return (nameEn || nameVn).trim();
}
